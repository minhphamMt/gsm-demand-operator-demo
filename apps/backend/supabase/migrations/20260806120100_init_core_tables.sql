-- =============================================================================
-- Đồng bộ auth.users -> profiles
--
-- Spec §4.1: profiles là "hồ sơ mở rộng từ Supabase Auth". Trigger này là phần
-- nối kỹ thuật để bản ghi profiles tồn tại ngay khi có user; spec không mô tả
-- cơ chế nên phần lấy role từ user metadata là quy ước của nhóm, sửa được.
-- =============================================================================

create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, role, full_name, phone)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data ->> 'role', ''), 'DRIVER'),
    nullif(new.raw_user_meta_data ->> 'full_name', ''),
    coalesce(nullif(new.raw_user_meta_data ->> 'phone', ''), new.phone)
  )
  on conflict (id) do nothing;

  return new;
end
$$;

