-- =============================================================================
-- GSM-14 MVP — Bước 2/3: 16 bảng dữ liệu, khoá ngoại và index
-- Nguồn: docs/database-spec.md
--
-- NGUYÊN TẮC: chỉ ràng buộc những gì spec nói thẳng.
--   - CHECK giá trị chỉ đặt khi spec liệt kê đúng các mã đó.
--   - Cột trạng thái spec không nêu mã nào => VARCHAR tự do, không CHECK,
--     không DEFAULT. Thêm CHECK sau khi nhóm chốt từ vựng.
--   - Không thêm ràng buộc "cho chắc" (amount >= 0, batch_size > 0, ...).
--
-- Thứ tự tạo bảng tuân theo phụ thuộc khoá ngoại. Ràng buộc duy nhất đi ngược
-- chiều (supply_demand_cells -> campaigns) được thêm bằng ALTER ở cuối file.
