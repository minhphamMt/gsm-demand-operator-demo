set search_path = public, extensions;

-- =============================================================================
-- NHÓM 1 — Tài khoản, tài xế và bản đồ
-- =============================================================================

-- 1. profiles ----------------------------------------------------------------
create table public.profiles (
  id           uuid primary key references auth.users (id) on delete cascade,
  -- Spec §2 liệt kê đúng hai vai trò.
  role         varchar(20)  not null check (role in ('OPERATOR', 'DRIVER')),
  full_name    text,
  phone        varchar(20),
  avatar_url   text,
  is_active    boolean      not null default true,
  created_at   timestamptz  not null default now(),
  updated_at   timestamptz  not null default now()
);

comment on table public.profiles is
  'Hồ sơ mở rộng từ Supabase Auth. FK trung tâm cho tài xế, người duyệt và người tạo campaign.';

create index idx_profiles_role on public.profiles (role) where is_active;

-- 2. h3_cells ----------------------------------------------------------------
create table public.h3_cells (
  h3_index       varchar(20) primary key,
  -- 0..15 là định nghĩa của hệ H3, không phải suy đoán về thiết kế.
  resolution     smallint    not null check (resolution between 0 and 15),
  district_code  varchar(20),
  district_name  text,
  center_point   geography(Point, 4326),
  boundary       geography(Polygon, 4326),
  is_active      boolean     not null default true
);

comment on table public.h3_cells is
  'Danh mục cell lục giác cố định (Hà Nội) dùng cho heatmap và lọc không gian nhanh.';

create index idx_h3_cells_district  on public.h3_cells (district_code) where is_active;
create index idx_h3_cells_boundary  on public.h3_cells using gist (boundary);
create index idx_h3_cells_center    on public.h3_cells using gist (center_point);

-- =============================================================================
-- NHÓM 2 — Cung–cầu
-- =============================================================================

-- 3. supply_demand_snapshots -------------------------------------------------
create table public.supply_demand_snapshots (
  id             bigint      generated by default as identity primary key,
  captured_at    timestamptz not null,
  data_source    varchar(30),
  scenario_code  varchar(50),
  total_demand   integer,
  total_supply   integer,
  created_at     timestamptz not null default now()
);

comment on table public.supply_demand_snapshots is
  'Header của mỗi lần persist cung–cầu. Nguồn tổng hợp cho heatmap, model_inputs, hotspot và proposal.';

create index idx_snapshots_captured_at on public.supply_demand_snapshots (captured_at desc);

-- 4. supply_demand_cells -----------------------------------------------------
create table public.supply_demand_cells (
  snapshot_id         bigint      not null references public.supply_demand_snapshots (id) on delete cascade,
  h3_index            varchar(20) not null references public.h3_cells (h3_index),
  current_demand      integer,
  predicted_demand    integer,
  available_supply    integer,
  -- Spec không định nghĩa công thức gap => cột thường, backend tự ghi.
  demand_supply_gap   integer,
  -- Spec chỉ nhắc tới ORANGE/RED, không liệt kê đủ thang => chưa đặt CHECK.
  severity_level      varchar(20),
  -- FK tới campaigns được thêm bằng ALTER ở cuối file.
  active_campaign_id  uuid,
  primary key (snapshot_id, h3_index)
);

comment on table public.supply_demand_cells is
  'Chỉ số cung–cầu theo snapshot × H3 cell. Nguồn dữ liệu chính của heatmap hiện tại.';

create index idx_sd_cells_h3       on public.supply_demand_cells (h3_index);
create index idx_sd_cells_severity on public.supply_demand_cells (snapshot_id, severity_level);

-- =============================================================================
-- NHÓM 3 — Phát hiện và ra quyết định
