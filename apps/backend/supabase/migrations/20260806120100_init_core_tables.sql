-- 5. hotspots ----------------------------------------------------------------
create table public.hotspots (
  id                   uuid        primary key default gen_random_uuid(),
  snapshot_id          bigint      references public.supply_demand_snapshots (id) on delete set null,
  -- Spec không liệt kê mã trạng thái hotspot => chưa đặt CHECK/DEFAULT.
  status               varchar(30),
  affected_h3_indexes  text[],
  geofence             geography(Polygon, 4326),
  shortage_count       integer,
  severity_level       varchar(20),
  cause_code           varchar(50),
  expected_start_at    timestamptz,
  expected_end_at      timestamptz,
  detected_at          timestamptz not null default now(),
  resolved_at          timestamptz
);

comment on table public.hotspots is
  'Vùng thiếu xe được phát hiện từ snapshot hoặc kết quả Model. Đầu vào để tạo proposal.';

create index idx_hotspots_detected on public.hotspots (detected_at desc);
create index idx_hotspots_status   on public.hotspots (status, detected_at desc);
create index idx_hotspots_snapshot on public.hotspots (snapshot_id);
create index idx_hotspots_h3       on public.hotspots using gin (affected_h3_indexes);
create index idx_hotspots_geofence on public.hotspots using gist (geofence);

-- 6. proposals ---------------------------------------------------------------
create table public.proposals (
  id                   uuid         primary key default gen_random_uuid(),
  hotspot_id           uuid         references public.hotspots (id) on delete set null,
  input_snapshot_id    bigint       references public.supply_demand_snapshots (id) on delete set null,

  -- Versioning: spec yêu cầu "giữ version, không ghi đè proposal đã duyệt".
  root_proposal_id     uuid         references public.proposals (id) on delete set null,
  parent_proposal_id   uuid         references public.proposals (id) on delete set null,
  version              integer,

  -- Spec §4.3 liệt kê đúng bốn nguồn sinh phương án.
  generator_type       varchar(20)  not null
                         check (generator_type in ('MOCK', 'RULE_BASED', 'AGENT', 'MANUAL')),
  generator_version    varchar(50),

  -- Spec nhắc APPROVED/REJECTED nhưng không liệt kê đủ vòng đời => chưa CHECK.
  status               varchar(30),
  policy_status        varchar(30),

  target_h3_indexes    text[],
  target_geofence      geography(Polygon, 4326),

  source_plan          jsonb,
  target_driver_count  integer,
  offer_count          integer,

  window_start_at      timestamptz,
  window_end_at        timestamptz,

  bonus_amount         numeric(12, 2),
  fare_multiplier      numeric(4, 2),
  estimated_cost       numeric(14, 2),

  simulation_details   jsonb,
  explanation          text,

  reviewed_by          uuid         references public.profiles (id) on delete set null,
  reviewed_at          timestamptz,
  review_note          text,

  created_at           timestamptz  not null default now(),
  updated_at           timestamptz  not null default now()
);

comment on table public.proposals is
  'Mỗi row là MỘT PHIÊN BẢN phương án. Không ghi đè proposal đã duyệt — tạo version mới.';

create index idx_proposals_hotspot on public.proposals (hotspot_id);
create index idx_proposals_status  on public.proposals (status, created_at desc);
create index idx_proposals_root    on public.proposals (root_proposal_id, version desc);

-- 7. campaigns ---------------------------------------------------------------
create table public.campaigns (
  id                   uuid         primary key default gen_random_uuid(),
  proposal_id          uuid         not null references public.proposals (id),
  -- Spec chỉ nêu TARGET_REACHED ("chỉ dừng tuyển, không tự kết thúc campaign"),
  -- không liệt kê đủ vòng đời => chưa đặt CHECK.
  status               varchar(30),

  target_h3_indexes    text[],
  geofence             geography(Polygon, 4326),
  navigation_target    geography(Point, 4326),

  target_driver_count  integer,
  batch_size           integer,

  start_at             timestamptz,
  end_at               timestamptz,
  reward_cutoff_at     timestamptz,

  bonus_amount         numeric(12, 2),
  fare_multiplier      numeric(4, 2),
  budget_limit         numeric(14, 2),
  budget_used          numeric(14, 2),

  created_by           uuid         references public.profiles (id) on delete set null,
  completed_at         timestamptz,
  created_at           timestamptz  not null default now(),
  updated_at           timestamptz  not null default now()
);

comment on table public.campaigns is
  'Bản triển khai được khoá từ proposal đã duyệt. TARGET_REACHED chỉ dừng tuyển thêm tài xế.';

create index idx_campaigns_status   on public.campaigns (status, start_at desc);
create index idx_campaigns_proposal on public.campaigns (proposal_id);
create index idx_campaigns_geofence on public.campaigns using gist (geofence);
create index idx_campaigns_h3       on public.campaigns using gin (target_h3_indexes);

