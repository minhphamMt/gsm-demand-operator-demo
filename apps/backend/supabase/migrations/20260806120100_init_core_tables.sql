-- 8. driver_offers -----------------------------------------------------------
create table public.driver_offers (
  id            uuid        primary key default gen_random_uuid(),
  campaign_id   uuid        not null references public.campaigns (id) on delete cascade,
  driver_id     uuid        not null references public.profiles (id) on delete cascade,
  batch_no      integer,
  -- Spec §5.1 liệt kê đúng năm trạng thái funnel: sent/viewed/accepted/declined/expired.
  status        varchar(20) not null
                  check (status in ('SENT', 'VIEWED', 'ACCEPTED', 'DECLINED', 'EXPIRED')),
  distance_m    integer,
  eta_seconds   integer,
  sent_at       timestamptz,
  viewed_at     timestamptz,
  responded_at  timestamptz,
  expires_at    timestamptz,
  created_at    timestamptz not null default now(),
  -- Spec §4.4: "chống gửi trùng".
  constraint uq_driver_offers_campaign_driver unique (campaign_id, driver_id)
);

comment on table public.driver_offers is
  'Lời mời cá nhân gửi tài xế; tách khỏi trạng thái di chuyển (xem campaign_participations).';

create index idx_offers_driver_open on public.driver_offers (driver_id, sent_at desc)
  where status in ('SENT', 'VIEWED');
create index idx_offers_campaign    on public.driver_offers (campaign_id, batch_no, status);
create index idx_offers_expiring    on public.driver_offers (expires_at)
  where status in ('SENT', 'VIEWED');

-- 9. campaign_participations -------------------------------------------------
create table public.campaign_participations (
  id                    uuid        primary key default gen_random_uuid(),
  campaign_id           uuid        not null references public.campaigns (id) on delete cascade,
  driver_id             uuid        not null references public.profiles (id) on delete cascade,
  offer_id              uuid        references public.driver_offers (id) on delete set null,

  -- Spec §4.4 nêu bốn mốc "accepted, en-route, verified, activated" và hai tình
  -- huống hỏng "no-show / location lost"; §5.2 xác nhận tên EN_ROUTE /
  -- ARRIVED_VERIFIED / ACTIVATED.
  status                varchar(20) not null
                          check (status in ('ACCEPTED', 'EN_ROUTE', 'ARRIVED_VERIFIED',
                                            'ACTIVATED', 'NO_SHOW', 'LOCATION_LOST')),
  eligibility_status    varchar(30),

  slot_deadline_at      timestamptz,
  arrival_deadline_at   timestamptz,

  accepted_at           timestamptz,
  en_route_at           timestamptz,
  arrived_verified_at   timestamptz,
  activated_at          timestamptz,

  first_inside_at       timestamptz,
  dwell_seconds         integer,
  last_location         geography(Point, 4326),
  last_h3_index         varchar(20),
  route                 jsonb,

  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now(),
  -- Hệ quả của "chống gửi trùng" trên driver_offers: mỗi tài xế tối đa một
  -- lượt tham gia cho mỗi campaign.
  constraint uq_participation_campaign_driver unique (campaign_id, driver_id)
);

comment on table public.campaign_participations is
  'Slot và quá trình tài xế tới vùng. Tạo khi offer được chấp nhận.';

create index idx_participations_driver   on public.campaign_participations (driver_id, created_at desc);
create index idx_participations_campaign on public.campaign_participations (campaign_id, status);
create index idx_participations_deadline on public.campaign_participations (arrival_deadline_at)
  where status in ('ACCEPTED', 'EN_ROUTE');

-- 10. trips ------------------------------------------------------------------
